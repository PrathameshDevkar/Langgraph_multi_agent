import operator
from dotenv import load_dotenv
from pydantic import BaseModel
from typing import Annotated, Literal
from langchain_core.messages import SystemMessage, ToolMessage, HumanMessage, AIMessage
from langchain_google_genai import ChatGoogleGenerativeAI
from langgraph.graph import StateGraph, add_messages, END
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_core.tools import tool, InjectedToolCallId
from langgraph.checkpoint.memory import MemorySaver
from datetime import datetime
from langgraph.types import Command, RunnableConfig
from langgraph_agent.multi_agent.agents.researcher import graph as research_agent
from langgraph_agent.multi_agent.agents.copywriter import graph as copywriter_agent

import logging
import os

load_dotenv()

logger = logging.getLogger(__name__)

api_key= os.getenv("google_gemini_api_key")
#Load the supervisor prompt
supervisor_prompt= open("langgraph_agent/multi_agent/prompts/supervisor.md", "r").read()


class SupervisorState(BaseModel):
    """
    The state of the supervisor agent.
    The research_reports attribute is shared with the copywriter agent. this allows us to share the resaerch reports between reearch and copywriter agent.
    """
    message: Annotated[list, add_messages]= []
    research_reports: Annotated[list, operator.add]=[]
    task_description: str | None = None

@tool
async def handoff_to_subagent(
    agent_name: Literal["researcher", "copywriter"],
    task_description: str,
    tool_call_id: Annotated[str, InjectedToolCallId]
):
    """
    Assigns a task to a sub-agent: researcher or copywriter

    args:
        agent_name: The name of the agent to handoff the task to. Valid agent names are researcher and copywriter.
        task_description: The description of the task to be completed.
    """
    #Construct the update schema for the command premitive
    # we're specifying to update the task description in the state and add a tool message to the conversation to let the supervisor know the task has been handed off.
    update= {
        "task_description": task_description,
        "messages": [ToolMessage(
            name= f"handoff_to_{agent_name}",
            content= f"successfully handed off to {agent_name}",
            tool_call_id= tool_call_id
        )]
    }

    #Return the command primitive with the update to the state and specifying the next node to go
    return Command(
        goto=f"call_{agent_name}",
        update=update
    )

async def call_researcher(state: SupervisorState, config= RunnableConfig):
    """
    Call the research agent.
    This agent is invoke only with the task description generated by the supervisor agent, so the context window is not cluttered by the conversation history of the supervisor.
    """
    research_response = await research_agent.ainvoke(
        input= {
            "messages":[HumanMessage(content= state.task_description)]
        },
        config= config
    )

    logger.info(
        "\n\nresearch response is:%s\n\n",
        research_response
    )
    ai_message= AIMessage(name= "researcher", content= research_response["messages"][-1].content)

    return{
        "research_reports":research_response["research_reports"],
        "messages":[ai_message]
    }

async def call_copywriter(state:SupervisorState, config: RunnableConfig):
    """
    Call the copywriter agent.
    This agent is only invoked by the task description generated by the supervisor, and the research reports generated by the researcher agent. 
    """
    copywriter_response= await copywriter_agent.ainvoke(
        input={
            "messages":[HumanMessage(content= state.task_description)],
            "research_reports": state.research_reports
        },
        config= config
    )

    ai_message= AIMessage(name= "copywriter", content= copywriter_response["messages"][-1].content)

    return {"messages": [ai_message]}

llm = ChatGoogleGenerativeAI(model= "gemini-3.5-flas-lite", api_key= api_key)
tools= [handoff_to_subagent]
llm_with_tools= llm.bind_tools(tools, parallel_tool_calls= False)

async def supervisor(state: SupervisorState):
    """The main supervisor agent"""
    response= await llm_with_tools.ainvoke([
        SystemMessage(content= supervisor_prompt.format(current_datetime= datetime.now()))
    ] + state.messages)
    logger.info(
        "\n\nsupervisor agent response:%s\n\n",
        response
    )
    return {"messages":[response]}

builder = StateGraph(SupervisorState)

builder.add_node("supervisor",supervisor)
builder.add_node("supervisor_toolnode", ToolNode(tools))
builder.add_node("call_researcher",call_researcher)
builder.add_node("call_copywriter",call_copywriter)

builder.set_entry_point("supervisor")
builder.add_conditional_edges(
    "supervisor",
    tools_condition,{
        "tools": "supervisor_toolnode",
        END:END
    }
)

# Add explicit paths from the toolnode to your subagent nodes
# This tells the compiler that the ToolNode can route to these destinations
builder.add_conditional_edges(
    "supervisor_toolnode",
    lambda state: None, # This fallback is handled dynamically by Command(goto=...)
    {
        "call_researcher": "call_researcher",
        "call_copywriter": "call_copywriter",
        "supervisor": "supervisor"
    }
)

builder.add_edge("call_researcher","supervisor")
builder.add_edge("call_copywriter","supervisor")

graph = builder.compile(checkpointer= MemorySaver())

print(graph.get_graph().edges)


